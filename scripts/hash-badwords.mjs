// Reads src/config/badwords.local.txt (gitignored, one word per line) and writes
// src/config/badwords.hashed.ts with SHA-256 hashes of the lowercased words.
// Usage: npm run hash-badwords
import { createHash } from 'node:crypto';
import { existsSync, readFileSync, writeFileSync } from 'node:fs';

const input = new URL('../src/config/badwords.local.txt', import.meta.url);
const output = new URL('../src/config/badwords.hashed.ts', import.meta.url);

if (!existsSync(input)) {
  console.error('Missing src/config/badwords.local.txt (one word per line). Nothing written.');
  process.exit(1);
}

const words = readFileSync(input, 'utf8')
  .split('\n')
  .map((line) => line.trim().toLowerCase())
  .filter((line) => line && !line.startsWith('#'));

const hashes = [...new Set(words)]
  .map((word) => createHash('sha256').update(word, 'utf8').digest('hex'))
  .sort();

writeFileSync(
  output,
  `// GENERATED by scripts/hash-badwords.mjs. Do not edit by hand.
// SHA-256 hashes of lowercased words from src/config/badwords.local.txt (gitignored).
export const badWordHashes: readonly string[] = ${JSON.stringify(hashes, null, 2)};
`,
);

console.log(`Wrote ${hashes.length} hashes to src/config/badwords.hashed.ts`);
